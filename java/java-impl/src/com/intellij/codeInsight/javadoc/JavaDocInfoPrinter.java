package com.intellij.codeInsight.javadoc;

import com.intellij.lang.Language;
import com.intellij.openapi.editor.markup.TextAttributes;
import com.intellij.openapi.project.Project;
import com.intellij.openapi.util.NlsSafe;
import com.intellij.psi.PsiClass;
import com.intellij.psi.PsiElement;
import com.intellij.psi.javadoc.PsiDocComment;
import org.jetbrains.annotations.Contract;
import org.jetbrains.annotations.Nls;
import org.jetbrains.annotations.Nullable;
import org.jspecify.annotations.NullMarked;

import java.net.URL;

/// The printer defines how the output produced by [JavaDocInfoGenerator] is stylized
@NullMarked
@SuppressWarnings("UnusedReturnValue")
public interface JavaDocInfoPrinter extends JavaDocInfoLinkPrinter {

  /// Describe the type of code block to be printed. Is a reflection of the tags in the input comment
  enum CodeBlockType {
    PRE_CODE,
    BLOCKQUOTE_PRE
  }

  String LT = "&lt;";
  String GT = "&gt;";
  String NBSP = "&nbsp;";

  /// The doc comment can be preprocessed before being passed to the [JavaDocInfoGenerator]
  default PsiDocComment preProcess(PsiDocComment docComment) {
    return docComment;
  }

  /// The String generated by the [JavaDocInfoGenerator] + printer to post process before being displayed
  default @Nls @Nullable String postProcess(StringBuilder generatedDocument, Project project, @Nullable PsiElement context) {
    return generatedDocument.toString();
  }

  /// Print a character that may need escaping in the target format.
  @Contract("_, _ -> param1")
  default StringBuilder printEscapableChar(StringBuilder builder, char character) {
    return builder.append(getEscapableChar(character));
  }

  /// Variant of [printEscapableChar] that doesn't modify a [StringBuilder]
  String getEscapableChar(char character);

  /// Escape the input string if necessary for the output format.
  String escapeIfNeeded(String input);

  /// Print a paragraph break.
  @Contract("_ -> param1")
  StringBuilder printParagraph(StringBuilder builder);

  /// Print a line break.
  @Contract("_ -> param1")
  StringBuilder printLineBreak(StringBuilder builder);

  /// Print the beginning of a definition block.
  @Contract("_ -> param1")
  StringBuilder printDefinitionStart(StringBuilder builder);

  /// Print the end of a definition block.
  @Contract("_ -> param1")
  StringBuilder printDefinitionEnd(StringBuilder builder);

  /// Print the beginning of the content section.
  @Contract("_ -> param1")
  StringBuilder printContentStart(StringBuilder builder);

  /// Print the end of the content section.
  @Contract("_ -> param1")
  StringBuilder printContentEnd(StringBuilder builder);

  /// Print the beginning of the sections block.
  @Contract("_ -> param1")
  StringBuilder printSectionsStart(StringBuilder builder);

  /// Print the end of the sections block.
  @Contract("_ -> param1")
  StringBuilder printSectionsEnd(StringBuilder builder);

  /// Print the beginning of a section header.
  @Contract("_ -> param1")
  StringBuilder printSectionHeaderStart(StringBuilder builder);

  /// Print the separator between a section header and its content.
  @Contract("_ -> param1")
  StringBuilder printSectionSeparator(StringBuilder builder);

  /// Print the end of a section.
  @Contract("_ -> param1")
  StringBuilder printSectionEnd(StringBuilder builder);

  /// Print the beginning of grayed text.
  @Contract("_ -> param1")
  StringBuilder printGrayedStart(StringBuilder builder);

  /// Print the end of grayed text.
  @Contract("_ -> param1")
  StringBuilder printGrayedEnd(StringBuilder builder);

  /// Print information about the element containing the documented element.
  @Contract("_,_,_,_ -> param1")
  StringBuilder printContainerInfo(StringBuilder builder, @Nullable PsiElement element, String ownerLink, boolean ownerLinkIsCode);

  /// Print the heading for the classes listed in a package.
  @Contract("_,_ -> param1")
  StringBuilder printPackageClassesStart(StringBuilder builder, @Nls String heading);

  /// Print a class entry in a package's class list.
  @Contract("_,_,_ -> param1")
  StringBuilder printPackageClass(StringBuilder builder, PsiClass psiClass, @NlsSafe String link);

  /// Flush buffered content into the generated document.
  @Contract(mutates = "param1, param2")
  void flushSubBuffer(StringBuilder buffer, StringBuilder subBuffer, boolean flushAsMarkdown);

  /// Print potentially highlighted text. Typical use is code block text
  @Contract("_,_,_,_,_,_ -> param1")
  StringBuilder printHighlightedText(StringBuilder builder,
                                     boolean doHighlighting,
                                     Project project,
                                     Language language,
                                     @Nullable String codeSnippet,
                                     float highlightSaturation);


  /// Print stylized text. Typical use is declaration text
  @Contract("_,_,_,_,_ -> param1")
  StringBuilder printStylizedText(StringBuilder builder,
                                  boolean doHighlighting,
                                  TextAttributes attributes,
                                  @Nullable String value,
                                  float highlightSaturation);

  /// Print a link to a PSI element.
  @Contract("_,_,_,_ -> param1")
  StringBuilder printLink(StringBuilder builder,
                          PsiElement targetElement,
                          @Nullable String label,
                          boolean plainLink);

  /// Print a link whose destination is already resolved.
  @Contract("_,_,_,_ -> param1")
  StringBuilder printLink(StringBuilder builder,
                          String target,
                          @Nullable String label,
                          boolean plainLink);

  /// Print a link that could not be resolved.
  @Contract("_,_ -> param1")
  StringBuilder printUnresolvedLink(StringBuilder builder, String label);

  /// Print inline code.
  @Contract("_,_,_,_ -> param1")
  StringBuilder printInlineCode(StringBuilder builder,
                                Project project,
                                @Nullable Language language,
                                String codeSnippet);

  /// Print a standalone code block.
  @Contract("_,_,_,_ -> param1")
  StringBuilder printCodeBlock(StringBuilder builder,
                               Project project,
                               @Nullable Language language,
                               String codeSnippet);


  @Contract("_,_,_ -> param1")
  default StringBuilder printCodeBlockStart(StringBuilder builder, @Nullable String id, Language language) {
    return printCodeBlockStart(builder, id, language, CodeBlockType.PRE_CODE);
  }

  /// Start a code block whose body is generated separately.
  ///
  /// @param id If supported, an identifier for the code block.
  @Contract("_,_,_,_ -> param1")
  StringBuilder printCodeBlockStart(StringBuilder builder, @Nullable String id, Language language, CodeBlockType type);


  @Contract("_ -> param1")
  default StringBuilder printCodeBlockEnd(StringBuilder builder) {
    return printCodeBlockEnd(builder, CodeBlockType.PRE_CODE);
  }

  /// Finish a code block started by [#printCodeBlockStart].
  @Contract("_,_ -> param1")
  StringBuilder printCodeBlockEnd(StringBuilder builder, CodeBlockType type);

  /// Print bold text.
  @Contract("_,_ -> param1")
  StringBuilder printBoldText(StringBuilder builder, String value);

  /// Print italic text.
  @Contract("_,_ -> param1")
  StringBuilder printItalicText(StringBuilder builder, String value);

  /// Print an annotation hint.
  @Contract("_,_ -> param1")
  StringBuilder printAnnotationHint(StringBuilder builder, boolean isInferred);

  @Contract("_,_ -> param1")
  StringBuilder printParameterName(StringBuilder builder, String presentableName);

  /// Print the document prologue.
  @Contract("_,_ -> param1")
  StringBuilder printPrologue(StringBuilder builder, @Nullable URL baseUrl);

  /// Utility method for impl to have escaped chars
  static String escapeChar(char character) {
    return switch (character) {
      case '<' -> LT;
      case '>' -> GT;
      case ' ' -> NBSP;
      default -> throw new IllegalStateException("Unexpected value: " + character);
    };
  }
}