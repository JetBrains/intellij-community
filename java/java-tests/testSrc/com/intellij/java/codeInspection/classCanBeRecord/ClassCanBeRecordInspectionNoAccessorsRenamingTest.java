@TestApplication
public class ClassCanBeRecordInspectionNoAccessorsRenamingTest {
  private static final String TEST_DATA_PATH = JavaTestUtil.getJavaTestDataPath() + "/inspection/classCanBeRecord/noAccessorsRenaming";
  private static final TestFixture<LightJavaProject> projectFixture = lightJavaProjectFixture(LightJavaCodeInsightFixtureTestCase.JAVA_21);
  private final TestFixture<LightQuickFixFixture> quickFixFixture = lightQuickFixFixture(
    projectFixture, TEST_DATA_PATH, () -> List.of(new ClassCanBeRecordInspection(ConversionStrategy.DO_NOT_SUGGEST, false)));

  static List<String> files() {
    return lightQuickFixTestFiles(TEST_DATA_PATH);
  }

  @ParameterizedTest(name = "{argumentSetNameOrArgumentsWithNames}")
  @MethodSource("files")
  void parameterized(String fileName) {
    BaseRefactoringProcessor.ConflictsInTestsException.withIgnoredConflicts(() -> quickFixFixture.get().doTest(fileName));
  }
}
