import com.intellij.testFramework.junit5.fixture.TestFixture;
import org.junit.jupiter.params.ParameterizedTest;
import org.junit.jupiter.params.provider.MethodSource;

import java.util.List;

import static com.intellij.codeInsight.daemon.quickFix.LightQuickFixFixtureKt.lightQuickFixFixture;
import static com.intellij.codeInsight.daemon.quickFix.LightQuickFixFixtureKt.lightQuickFixTestFiles;
import static com.intellij.testFramework.fixtures.LightJavaFixturesKt.lightJavaProjectFixture;
import static com.intellij.testFramework.fixtures.LightJavaFixturesKt.lightJavaTestDescriptor;

@TestApplication
public class InvertIfConditionTest {
  private static final String BASE_PATH = "/codeInsight/invertIfCondition/";
  private static final String TEST_DATA_PATH = JavaTestUtil.getJavaTestDataPath() + BASE_PATH;
  private static final TestFixture<LightJavaProject> projectFixture = lightJavaProjectFixture(lightJavaTestDescriptor());
  private final TestFixture<LightQuickFixFixture> quickFixFixture =
    lightQuickFixFixture(projectFixture, TEST_DATA_PATH, List::of, LightQuickFixOptions.DEFAULT.withActionAvailableAfterExecution());

  static List<String> files() {
    return lightQuickFixTestFiles(TEST_DATA_PATH);
  }

  @ParameterizedTest(name = "{argumentSetNameOrArgumentsWithNames}")
  @MethodSource("files")
  void parameterized(String fileName) {
    LightQuickFixFixture quickFix = quickFixFixture.get();
    ActionHint hint = quickFix.configure(fileName);
    String contents = ReadAction.computeBlocking(() -> quickFix.getFixture().getFile().getText());
    final CommonCodeStyleSettings settings =
      CodeStyle.getSettings(quickFix.getFixture().getProject()).getCommonSettings(JavaLanguage.INSTANCE);
    boolean myElseOnNewLine = settings.ELSE_ON_NEW_LINE;
    settings.ELSE_ON_NEW_LINE = !contents.contains("else on the same line");
    try {
      quickFix.checkAction(fileName, hint);
    }
    finally {
      CodeStyle.getSettings(quickFix.getFixture().getProject()).getCommonSettings(JavaLanguage.INSTANCE).ELSE_ON_NEW_LINE = myElseOnNewLine;
    }
  }
}
