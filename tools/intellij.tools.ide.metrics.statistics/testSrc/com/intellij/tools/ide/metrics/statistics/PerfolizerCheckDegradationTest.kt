  private fun isReliable(historyDescriptor: List<Pair<Int, Int>>, currentDescriptor: List<Pair<Int, Int>>): Boolean {
    val random = Random(1729)

    fun build(descriptor: List<Pair<Int, Int>>): List<Double> {
      val list = mutableListOf<Double>()
      for (pair in descriptor) {
        val (count, mean) = pair
        for (i in 1..count)
          list.add(random.nextInt(mean - 100, mean + 100).toDouble())
      }
      return list
    }

    val history = build(historyDescriptor)
    val current = build(currentDescriptor)
    val result = Perfolizer.PerformanceChecker.check(history, current, isReliableCheck = true)
    return !result.muteReasons.contains("Metric is unreliable")
  }

