class PerfolizerCheckDegradationTest {

  private fun getVerdict(history: List<Int>, current: List<Int>): BenchmarkVerdict {
    val result = Perfolizer.PerformanceChecker.check(history.map { it.toDouble() }, current.map { it.toDouble() }, false)
    println("shift = ${String.format("%.2f", result.change.shift)}")
    println("ratio = ${String.format("%.2f", result.change.ratio)}")
    println("effectSize = ${String.format("%.2f", result.change.effectSize)}")
    println("verdict = ${result.verdict}")
    return result.verdict
  }

  private fun shouldNotBeFailure(history: List<Int>, current: List<Int>) {
    assertNotEquals(BenchmarkVerdict.SLOWER_SEVERE, getVerdict(history, current))
  }

  private fun shouldNotBeFailureAnySize(history: List<Int>, current: List<Int>) {
    for (i in 1..current.size)
      shouldNotBeFailure(history, current.take(i))
  }

  private fun shouldBeFailure(history: List<Int>, current: List<Int>) {
    assertEquals(BenchmarkVerdict.SLOWER_SEVERE, getVerdict(history, current))
  }

  private fun shouldBeOk(history: List<Int>, current: List<Int>) {
    assertEquals(BenchmarkVerdict.STEADY, getVerdict(history, current))
  }

  private fun shouldBeFailurePrecise(history: List<Int>, current: List<Int>) {
    fun check(iteration: Int) {
      val verdict = getVerdict(history, current.take(iteration))
      println("Iteration $iteration: $verdict")
      if (iteration == current.size)
        assertEquals(BenchmarkVerdict.SLOWER_SEVERE, verdict)
      else
        assertNotEquals(BenchmarkVerdict.SLOWER_SEVERE, verdict)
    }
    for (i in 1..current.size)
      check(i)
  }

