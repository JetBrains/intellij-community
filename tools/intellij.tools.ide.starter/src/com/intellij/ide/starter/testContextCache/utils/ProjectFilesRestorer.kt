package com.intellij.ide.starter.testContextCache.utils

import com.intellij.tools.ide.util.common.logError
import com.intellij.tools.ide.util.common.logOutput
import java.nio.file.Path
import kotlin.io.path.exists
import kotlin.io.path.isDirectory

/**
 * Creates a reusable snapshot of tracked project files and restores them between UI tests.
 *
 * Project metadata inside the project directory, including `.idea`, is tracked by default.
 * The build roots in [excludedDirectories] are not tracked. By default these are the generated build roots,
 * because their contents are not part of the asserted test state and may contain short-lived temporary files.
 */
class ProjectFilesRestorer(
  projectPath: Path,
  private val excludedDirectories: Set<String> = DEFAULT_EXCLUDED_DIRECTORIES,
) : AutoCloseable {
  private val projectPath = projectPath.toAbsolutePath().normalize()
  private var snapshot: FileTreeSnapshot? = null

  init {
    require(this.projectPath.isDirectory()) { "Project path must point to an existing directory: ${this.projectPath}" }
    logOutput("ProjectFilesRestorer initialized for $projectPath")
  }

  /**
   * Captures an on-disk snapshot of tracked project files.
   *
   * @param base an earlier restorer of the same project. A file that has not changed since its snapshot is not copied
   * again. So [base] must stay open while this snapshot is in use.
   */
  fun captureSnapshot(base: ProjectFilesRestorer? = null) {
    deleteSnapshot()

    val snapshot = FileTreeSnapshot.capture(
      root = projectPath,
      shouldTrackDirectory = { relativePath -> !isExcludedBuildRoot(relativePath) },
      base = base?.let { checkNotNull(it.snapshot) { "The base snapshot is not captured for ${it.projectPath}" } },
    )
    this.snapshot = snapshot

    logOutput("ProjectFilesRestorer captured snapshot for $projectPath")
    logOutput("ProjectFilesRestorer snapshot directory: ${snapshot.snapshotDir}")
    logOutput("ProjectFilesRestorer tracked files: ${snapshot.trackedFilesCount}, shared with the base snapshot: ${snapshot.sharedFilesCount}")
    logOutput("ProjectFilesRestorer tracked directories: ${snapshot.trackedDirectoriesCount}")
  }

  /** Returns whether tracked project files differ from the latest snapshot. */
  fun hasChanges(): Boolean {
    val snapshot = snapshot ?: error("Project snapshot is not captured for $projectPath. Call captureSnapshot() before checking changes.")
    return snapshot.hasChanges()
  }

  /**
   * Restores the tracked files from the snapshot.
   *
   * @return whether the restore wrote to the project files.
   */
  fun restore(): Boolean {
    val snapshot = snapshot ?: error("Project snapshot is not captured for $projectPath. Call captureSnapshot() before restore().")
    val changes = snapshot.changes()
    snapshot.restoreTracked(projectPath, changes)
    logOutput(
      "ProjectFilesRestorer restored $projectPath: modified=${changes.modifiedFiles.size}, " +
      "recreated=${changes.deletedFiles.size}, removed=${changes.newFiles.size}"
    )
    return changes.hasChanges()
  }

  override fun close() {
    deleteSnapshot()
  }

  private fun deleteSnapshot() {
    val snapshot = snapshot ?: return
    runCatching {
      snapshot.close()
      logOutput("ProjectFilesRestorer deleted snapshot directory: ${snapshot.snapshotDir}")
    }.onFailure {
      logError("ProjectFilesRestorer failed to delete snapshot directory ${snapshot.snapshotDir}: ${it.message}")
    }.also {
      this.snapshot = null
    }
  }

  /**
   * A project can hold nested builds, so an excluded root can be at any depth. A nested `build` or `target` is a build
   * root only next to a build script or in `buildSrc`, because a source package can have the same name.
   */
  private fun isExcludedBuildRoot(relativePath: Path): Boolean {
    val name = relativePath.fileName?.toString() ?: return false
    if (name !in excludedDirectories) return false
    val parent = relativePath.parent ?: return true
    return name.startsWith(".") || parent.fileName.toString() == "buildSrc" ||
           BUILD_SCRIPTS.any { projectPath.resolve(parent).resolve(it).exists() }
  }

  companion object {
    /**
     * Top-level generated build directories excluded from project snapshotting by default.
     *
     * Reuse is intended to preserve user-meaningful project state, such as sources and project metadata.
     * Outputs under top-level `.kotlin`, `.gradle`, `build`, and `target` roots are typically regenerated by tooling and
     * are not part of the asserted test state, so tracking them would mostly add cost and false-positive changes.
     *
     * `@ReusedRun` keeps these roots on purpose, so a test of the class reuses the build output and the tool state of
     * the test before it. The prepared state of a cached context tracks them, see
     * [com.intellij.ide.starter.testContextCache.CachedTestContext.restorePreparedProjectFiles].
     */
    val DEFAULT_EXCLUDED_DIRECTORIES: Set<String> = setOf(".kotlin", ".gradle", "build", "target")

    private val BUILD_SCRIPTS = listOf("build.gradle", "build.gradle.kts", "settings.gradle", "settings.gradle.kts", "pom.xml")
  }
}
