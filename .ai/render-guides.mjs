async function loadPartialsFromDir(dir) {
  let entries;
  try {
    entries = await readdir(dir, {withFileTypes: true});
  } catch (error) {
    if (error && error.code === "ENOENT") {
      return new Map();
    }
    throw error;
  }
  const partials = new Map();
  for (const entry of entries) {
    if (!entry.isFile() || !entry.name.endsWith(".md")) {
      continue;
    }
    const name = entry.name.replace(/\.md$/, "");
    const path = join(dir, entry.name);
    const content = await readFile(path, "utf8");
    partials.set(name, {content: content.trimEnd(), path});
  }
  return partials;
}

async function loadPartials() {
  const partials = new Map();
  const sources = [partialsDir, sharedPartialsDir];
  for (const source of sources) {
    const next = await loadPartialsFromDir(source);
    for (const [name, partial] of next.entries()) {
      partials.set(name, partial);
    }
  }
  return partials;
}

function getPartialContent(name, partials) {
  const partial = partials.get(name);
  if (partial === undefined) {
    throw new Error(`Unknown partial: ${name}`);
  }

  const extensionPrefix = `${name}.`;
  const extensionContents = Array.from(partials.entries())
    .filter(([extensionName]) => extensionName.startsWith(extensionPrefix))
    .sort(([leftName], [rightName]) => leftName.localeCompare(rightName))
    .map(([, extensionContent]) => extensionContent);

  return [partial, ...extensionContents].join("\n");
}

export function applyPartials(text, partials) {
  return text.replace(partialPattern, (match, name) => {
    return getPartialContent(name, partials);
  });
}

const templateBlockPattern = /<!-- TEMPLATE:COMMENT -->[\s\S]*?<!-- \/TEMPLATE:COMMENT -->\n?/g;

function stripTemplateBlocks(text) {
  return text.replace(templateBlockPattern, "");
}

const toolBlockPattern = /<!--\s*IF_TOOL:([A-Z0-9_-]+)\s*-->([\s\S]*?)<!--\s*\/IF_TOOL:\1\s*-->/gi;

function applyToolBlocks(text, tool) {
  const normalizedTool = (tool ?? "").toUpperCase();
  return text.replace(toolBlockPattern, (match, blockTool, content) => {
    if (blockTool.toUpperCase() === normalizedTool) {
      return content;
    }
    return "";
  });
}

const editionBlockPattern = /<!--\s*IF_EDITION:([A-Z0-9_-]+)\s*-->([\s\S]*?)<!--\s*\/IF_EDITION:\1\s*-->/gi;
const wholeLineEditionBlockPattern =
  /^[ \t]*<!--\s*IF_EDITION:([A-Z0-9_-]+)\s*-->([^\n]*?)<!--\s*\/IF_EDITION:\1\s*-->[ \t]*\n/gim;
const unresolvedToolDirectivePattern = /<!--\s*\/?IF_TOOL:[^>]+-->/i;
const unresolvedEditionDirectivePattern = /<!--\s*\/?IF_EDITION:[^>]+-->/i;
const unresolvedTemplateCommentPattern = /<!--\s*\/?TEMPLATE:COMMENT\s*-->/i;

/**
 * Removes a line that holds one edition block for another edition, the newline included. The block
 * replacement alone leaves an empty line there, and an empty line ends the Markdown list the bullet
 * was in. Two lines never match: a line that pairs two editions, because the pair keeps one of the
 * two, and a block that spans lines, which the caller must write in an edition-only partial.
 */
function dropWholeLineEditionBlocks(text, normalizedEdition) {
  return text.replace(wholeLineEditionBlockPattern, (match, blockEdition) => {
    return blockEdition.toUpperCase() === normalizedEdition ? match : "";
  });
}

export function applyEditionBlocks(text, edition) {
  const normalizedEdition = (edition ?? "").toUpperCase();
  return dropWholeLineEditionBlocks(text, normalizedEdition).replace(
    editionBlockPattern,
    (match, blockEdition, content) => {
      if (blockEdition.toUpperCase() === normalizedEdition) {
        return content;
      }
      return "";
    },
  );
}

