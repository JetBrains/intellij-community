package com.intellij.terminal.emulator

import com.intellij.openapi.application.PathManager
import org.assertj.core.api.Assertions.assertThat
import org.junit.jupiter.params.ParameterizedTest
import org.junit.jupiter.params.provider.MethodSource
import java.nio.file.Files
import java.nio.file.Path
import kotlin.io.path.readText
import kotlin.io.path.writeText

/**
 * Replays recorded PTY output from real programs (tmux + htop, vim, fish, zsh completion, …) and from
 * vttest runs, and compares the resulting screen + scrollback against a golden dump.
 *
 * The recordings come from Alacritty's reference-test corpus (`alacritty_terminal/tests/ref`, Apache-2.0),
 * which captured the raw bytes those programs wrote to the pty; see `testData/alacritty/README.md`. Only
 * the byte streams are reused — the goldens are this emulator's own output, verified once against
 * Alacritty's recorded grid when they were created (see the README).
 *
 * What this adds over the hand-written tests in this package: length and mess. A single recording mixes
 * hundreds of sequences the way a real program emits them — partial repaints, alternate-screen switches,
 * scrolling regions, SGR churn — so it catches interactions no focused test sets up. The flip side is that
 * a failure points at a diff, not at a behavior, so read the diff before "fixing" the golden.
 *
 * To re-record after an intended behavior change:
 * `./tests.cmd --module intellij.terminal.emulator.tests --test com.intellij.terminal.emulator.AlacrittyReplayTest`
 * with `TERMINAL_EMULATOR_OVERWRITE_TESTDATA=true` set in the environment (or the
 * `terminal.emulator.overwrite.testdata` system property in an IDE run configuration), then review every
 * changed golden.
 */
class AlacrittyReplayTest {

  /** One recorded stream: the [name] of its `.recording` / `.txt` pair and the grid size it was captured at. */
  data class Recording(val name: String, val columns: Int, val rows: Int) {
    override fun toString(): String = "$name (${columns}x$rows)"
  }

  @ParameterizedTest(name = "{0}")
  @MethodSource("recordings")
  fun replayMatchesGolden(recording: Recording) {
    val bytes = Files.readAllBytes(testDataDir().resolve("${recording.name}.recording"))

    val wholeStream = replay(recording, bytes, chunkSize = bytes.size)
    // The same bytes split into small writes must land identically: the engine has to keep its parser and
    // UTF-8 decoder state across write() calls, which is how a real pty read loop delivers output.
    val chunked = replay(recording, bytes, chunkSize = 7)
    assertThat(chunked).describedAs("replay in 7-byte chunks must match the whole-stream replay").isEqualTo(wholeStream)

    val golden = testDataDir().resolve("${recording.name}.txt")
    if (OVERWRITE_TEST_DATA) {
      golden.writeText(wholeStream)
      return
    }
    assertThat(Files.exists(golden))
      .describedAs("missing golden ${golden.fileName}; re-run with $OVERWRITE_ENV=true to create it")
      .isTrue()
    assertThat(wholeStream).isEqualTo(golden.readText())
  }

  /** Feeds [bytes] to a fresh emulator in [chunkSize] slices and renders the result as the golden text. */
  private fun replay(recording: Recording, bytes: ByteArray, chunkSize: Int): String {
    createTerminalEmulator(TerminalSize(recording.columns, recording.rows)).use { emulator ->
      var offset = 0
      while (offset < bytes.size) {
        val end = minOf(offset + chunkSize, bytes.size)
        emulator.write(bytes.copyOfRange(offset, end))
        offset = end
      }
      return render(recording, emulator)
    }
  }

  private fun render(recording: Recording, emulator: TerminalEmulator): String = buildString {
    appendLine("# ${recording.name}: ${recording.columns}x${recording.rows}")
    appendLine("# Generated by AlacrittyReplayTest from testData/alacritty/${recording.name}.recording -- do not edit by hand.")
    appendLine("--- scrollback (${emulator.scrollbackRows} rows) ---")
    for (row in 0 until emulator.scrollbackRows) {
      appendLine(emulator.scrollbackLine(row).toStyledText().text)
    }
    appendLine("--- screen (${emulator.size.rows} rows) ---")
    for (row in 0 until emulator.size.rows) {
      appendLine(emulator.screenLine(row).toStyledText().text)
    }
    appendLine("--- state ---")
    appendLine("cursor: column ${emulator.cursor.column + 1}, row ${emulator.cursor.row + 1}")
    appendLine("alternateScreen: ${emulator.usingAlternateScreen}")
    appendLine("title: ${emulator.title}")
  }

  private fun testDataDir(): Path =
    Path.of(PathManager.getCommunityHomePath(), "plugins", "terminal", "emulator", "testData", "alacritty")

  companion object {
    private const val OVERWRITE_PROPERTY = "terminal.emulator.overwrite.testdata"
    private const val OVERWRITE_ENV = "TERMINAL_EMULATOR_OVERWRITE_TESTDATA"

    // tests.cmd forwards -D flags to the build-script JVM rather than to the test JVM, so the environment
    // variable is the one that works from the command line; the property is for IDE run configurations.
    private val OVERWRITE_TEST_DATA: Boolean =
      System.getProperty(OVERWRITE_PROPERTY).toBoolean() || System.getenv(OVERWRITE_ENV).toBoolean()

    /**
     * The vendored recordings and the grid size each was captured at (Alacritty's `size.json`); replaying at
     * another size would reflow the content and invalidate the golden.
     */
    @JvmStatic
    fun recordings(): List<Recording> = listOf(
      // full-program streams
      Recording("tmux_htop", 105, 29),
      Recording("tmux_git_log", 105, 29),
      Recording("vim_simple_edit", 80, 24),
      Recording("fish_cc", 105, 29),
      Recording("zsh_tab_completion", 105, 29),
      // vttest runs
      Recording("vttest_insert", 105, 29),
      Recording("vttest_scroll", 105, 29),
      Recording("vttest_tab_clear_set", 116, 31),
      // focused feature streams
      Recording("csi_rep", 105, 29),
      Recording("erase_in_line", 139, 33),
      Recording("selective_erasure", 10, 3),
      Recording("sgr", 139, 35),
      Recording("indexed_256_colors", 105, 29),
      Recording("hyperlinks", 140, 32),
      Recording("zerowidth", 139, 35),
      Recording("history", 105, 29),
      Recording("scroll_in_region_up_preserves_history", 80, 30),
      Recording("wrapline_alt_toggle", 139, 35),
      Recording("alt_reset", 106, 30),
    )
  }
}
