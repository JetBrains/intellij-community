package com.intellij.mermaid.jcef

import com.intellij.mermaid.api.MermaidRenderResult
import com.intellij.mermaid.api.appendTo
import com.intellij.mermaid.jcef.impl.decode
import kotlinx.browser.window
import kotlinx.coroutines.coroutineScope
import kotlinx.coroutines.ensureActive
import kotlinx.coroutines.flow.collectLatest
import kotlinx.coroutines.flow.map
import kotlinx.coroutines.flow.merge
import kotlinx.coroutines.flow.onStart
import org.w3c.dom.Element
import org.w3c.dom.HTMLElement
import org.w3c.dom.asList
import kotlin.time.ExperimentalTime
import kotlin.time.measureTime

private fun collectBlocks(): List<HTMLElement> {
  val nodes = window.document.querySelectorAll("div.mermaid").asList()
  // Just for sanity reason
  return nodes.filterIsInstance<HTMLElement>()
}

@OptIn(ExperimentalTime::class)
private suspend fun performRender() {
  val time = measureTime {
    val blocks = collectBlocks()
    forgetZoomIfBlockSetChanged(blocks.size)
    console.log("${blocks.size} blocks will be generated by mermaid")
    renderBlocks(blocks)
  }
  console.log("Generated all mermaid blocks in $time")
}

suspend fun renderBlocks(blocks: List<HTMLElement>) {
  coroutineScope {
    for (block in blocks) {
      // Cancellation-safe boundary: drop remaining stale blocks if a newer render arrived. A single
      // block's render is non-cancellable (renderBlock), so renders never overlap (shared global state).
      ensureActive()
      processBlock(block)
    }
  }
}

val nodeToCacheIdAndContent = mutableMapOf<Element, Pair<String, MermaidRenderResult>>()

suspend fun processBlock(block: HTMLElement) {
  block.removeAttribute("data-processed")
  val cacheId = block.getAttribute("data-cache-id")
  checkNotNull(cacheId) { "data-cache-id was not set for block" }
  val content = block.getAttribute("data-actual-fence-content")
  checkNotNull(content) { "data-actual-fence-content was not set for block" }

  val centre = block.scrollCentre()
  val cached = nodeToCacheIdAndContent[block]
  if (cached?.first == cacheId) {
    cached.second.appendTo(block)
  }
  else {
    val generated = renderBlock(block, cacheId, decode(content))
    if (generated != null) {
      nodeToCacheIdAndContent[block] = cacheId to generated
    }
  }
  applyZoom(block)
  block.restoreScrollCentre(centre)
}

private sealed interface PreviewUpdate {
  data object Patched : PreviewUpdate

  data class Resized(val widened: Boolean) : PreviewUpdate

  data class Refit(val block: Element) : PreviewUpdate
}

suspend fun markdownExtensionMain() {
  // Cached SVGs are pinned to their render-time max-width, so on a resize we drop the cache of the blocks
  // that have to refit and re-render those. A single collector serializes patches, resizes and refits so
  // mermaid renders never overlap.
  val patches = IncrementalDom.afterPatchEvents().map { PreviewUpdate.Patched }
  val resizes = bodyWidthChangeEvents().map { PreviewUpdate.Resized(widened = it) }
  val refits = zoomResetRequests().map { PreviewUpdate.Refit(it) }
  merge(patches, resizes, refits)
    .onStart { emit(PreviewUpdate.Patched) } // initial render
    .collectLatest { update ->
      when (update) {
        is PreviewUpdate.Refit -> refitBlock(update.block)
        is PreviewUpdate.Resized -> {
          dropCacheOfBlocksToRefit(update.widened)
          performRender()
        }
        PreviewUpdate.Patched -> performRender()
      }
    }
}

private fun dropCacheOfBlocksToRefit(widened: Boolean) {
  for (block in collectBlocks()) {
    if (shouldRefitAfterResize(block, widened)) {
      nodeToCacheIdAndContent.remove(block)
    }
  }
}

suspend fun refitBlock(block: Element) {
  val htmlBlock = block as? HTMLElement ?: return
  resetZoom(htmlBlock)
  nodeToCacheIdAndContent.remove(htmlBlock)
  processBlock(htmlBlock)
}
