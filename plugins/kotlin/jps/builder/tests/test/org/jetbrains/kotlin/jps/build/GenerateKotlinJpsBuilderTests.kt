package org.jetbrains.kotlin.jps.build

import com.intellij.openapi.application.PathManager
import java.nio.file.Path
import kotlin.io.path.isDirectory
import kotlin.io.path.isRegularFile
import kotlin.io.path.listDirectoryEntries
import kotlin.io.path.name
import kotlin.io.path.readText
import kotlin.io.path.writeText

/**
 * Writes [KotlinJpsIncrementalTestGenerated] from the union of the published test data and the overlay, see
 * [KotlinJpsTestData]. The groups and the exclusions follow `GenerateJpsPluginTests.kt` of the Kotlin repository.
 *
 * The "Generate Kotlin Tests" run configuration calls it, and `AllTestsGeneratedTest` checks that the class is up to date.
 */
fun main() {
  generateKotlinJpsBuilderTests()
}

/** @param isUpToDateCheck fail when the generated class differs, instead of writing it. */
fun generateKotlinJpsBuilderTests(isUpToDateCheck: Boolean = false) {
  val roots = listOf(KotlinJpsTestData.artifactRoot, KotlinJpsTestData.overlaySourceRoot).filter { it.isDirectory() }
  val content = render(GROUPS.flatMap { collectCases(it, roots) })

  val target = Path.of(PathManager.getCommunityHomePath(), OUTPUT_PATH)
  val existing = if (target.isRegularFile()) target.readText() else null
  if (existing == content) return
  check(!isUpToDateCheck) {
    "$target is out of date. Run the 'Generate Kotlin Tests' run configuration or org.jetbrains.kotlin.jps.build.GenerateKotlinJpsBuilderTests"
  }
  target.parent.toFile().mkdirs()
  target.writeText(content)
}

private const val OUTPUT_PATH = "plugins/kotlin/jps/builder/tests/test-gen/org/jetbrains/kotlin/jps/build/KotlinJpsIncrementalTestGenerated.java"

/** A group of cases. A [recursive] group has its cases in the leaf directories. */
private class Group(val path: String, val recursive: Boolean, val excluded: Regex? = null)

private val EXPECT = Regex("^.*Expect.*")

private val GROUPS = listOf(
  Group("incremental/pureKotlin", recursive = false, excluded = EXPECT),
  Group("incremental/classHierarchyAffected", recursive = false, excluded = EXPECT),
  Group("incremental/inlineFunCallSite", recursive = true),
  Group("incremental/withJava", recursive = true),
  Group("incremental/incrementalJvmCompilerOnly", recursive = true),
  Group("incremental/multiModule/withJavaUsedInKotlin", recursive = true),
  Group("incremental/scopeExpansion", recursive = true, excluded = Regex("^protectedBecomesPublicAccessedTroughChild")),
  Group("incremental/sealed", recursive = true),
  Group("incremental/resolution", recursive = true),
)

/** A case directory name has no dot, as in the Kotlin generator. */
private val CASE_NAME = Regex("^([^.]+)$")

private fun collectCases(group: Group, roots: List<Path>): List<String> {
  fun childDirectories(relativePath: String): Set<String> =
    roots.map { it.resolve(relativePath) }
      .filter { it.isDirectory() }
      .flatMap { dir -> dir.listDirectoryEntries().filter { it.isDirectory() }.map { it.name } }
      .filter { CASE_NAME.matches(it) }
      .toSortedSet()

  val result = ArrayList<String>()
  fun collect(relativePath: String) {
    for (name in childDirectories(relativePath)) {
      if (group.excluded?.matches(name) == true) continue
      val casePath = "$relativePath/$name"
      if (group.recursive && childDirectories(casePath).isNotEmpty()) {
        collect(casePath)
      }
      else if (isSupported(casePath, roots)) {
        result.add(casePath)
      }
    }
  }
  collect(group.path)
  return result
}

/** The builder compiles Kotlin/JVM only, and it rejects a cycle of modules. */
private fun isSupported(casePath: String, roots: List<Path>): Boolean {
  val caseDir = roots.reversed().map { it.resolve(casePath) }.firstOrNull { dir ->
    listOf("dependencies.txt", "_dependencies.txt").any { dir.resolve(it).isRegularFile() }
  } ?: return true
  val project = try {
    KotlinJpsTestProject.read(caseDir.toFile())
  }
  catch (_: IllegalStateException) {
    return false
  }
  return project?.hasCycle() != true
}

private fun render(cases: List<String>): String = buildString {
  appendLine("// Copyright 2000-2026 JetBrains s.r.o. and contributors. Use of this source code is governed by the Apache 2.0 license.")
  appendLine("package org.jetbrains.kotlin.jps.build;")
  appendLine()
  appendLine("import org.junit.jupiter.api.Test;")
  appendLine()
  appendLine("/** Generated by {@link GenerateKotlinJpsBuilderTests}. Do not modify it by hand. */")
  appendLine("@SuppressWarnings(\"all\")")
  appendLine("public class KotlinJpsIncrementalTestGenerated extends AbstractKotlinJpsIncrementalTest {")
  for ((index, case) in cases.withIndex()) {
    if (index > 0) appendLine()
    appendLine("  @Test")
    appendLine("  public void ${methodName(case)}() {")
    appendLine("    runTest(\"$case\");")
    appendLine("  }")
  }
  appendLine("}")
}

private fun methodName(casePath: String): String =
  "test" + casePath.removePrefix("incremental/").split('/').joinToString("_") { segment ->
    segment.replaceFirstChar { it.uppercaseChar() }.map { if (it.isJavaIdentifierPart()) it else '_' }.joinToString("")
  }
