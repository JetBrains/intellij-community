package org.jetbrains.idea.devkit.inspections.quickfix

import com.intellij.testFramework.fixtures.LightJavaProject
import com.intellij.testFramework.junit5.fixture.TestFixture
import com.intellij.testFramework.junit5.fixture.testFixture
import org.jetbrains.idea.devkit.inspections.internal.UseVirtualFileEqualsInspection

/**
 * Creates a [LightDevKitInspectionFixture] for one test. Declare it as an instance field.
 *
 * [fileExtension] is the extension of the test data files. [basePath] is the test data path under the community directory.
 * The fixture enables [UseVirtualFileEqualsInspection]. The project has the stub of `VirtualFile`.
 */
@JvmOverloads
fun useVirtualFileEqualsFixture(
  projectFixture: TestFixture<LightJavaProject>,
  fileExtension: String,
  basePath: String = "",
): TestFixture<LightDevKitInspectionFixture> = testFixture("useVirtualFileEqualsFixture") {
  val devKit = lightDevKitInspectionFixture(projectFixture, fileExtension, basePath).init()
  val fixture = devKit.fixture
  fixture.enableInspections(UseVirtualFileEqualsInspection())
  fixture.addClass("""
    package com.intellij.openapi.vfs;
    public abstract class VirtualFile {}
    """.trimIndent())
  initialized(devKit) {}
}
