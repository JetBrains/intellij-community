package com.intellij.tools.build.bazel.tmhAssertionsKotlinPlugin

import com.intellij.tools.build.bazel.jvmIncBuilder.tmh.TMHAssertionGenerator2
import org.jetbrains.kotlin.backend.jvm.extensions.ClassGenerator
import org.jetbrains.kotlin.backend.jvm.extensions.ClassGeneratorExtension
import org.jetbrains.kotlin.ir.declarations.IrClass

/**
 * Adds the threading model assertions during the code generation. The extension puts a [TmhAssertionsClassGenerator] in
 * front of the generator of every class that has an IR declaration, when the compile has `ThreadingAssertions`.
 * Otherwise it returns the generator of the compiler as it is.
 *
 * A class without an IR declaration is a copy of generated bytecode: the compiler makes one when it inlines a function
 * with an anonymous object. The copy keeps the calls of its source, so the extension does not wrap it.
 *
 * The assertion generators are those of the worker's instrumenter for the Kotlin output: the soft assertions, limited
 * to the assertion methods that the `ThreadingAssertions` class of the compile declares. The class does not change during
 * the compile, so the extension selects the generators once.
 *
 * @param threadingAssertions the `ThreadingAssertions` class of the compile
 * @param generateLineNumbers the plugin option `generateLineNumbers`
 */
internal class TmhAssertionsClassGeneratorExtension(
  private val threadingAssertions: ThreadingAssertionsDeclaration,
  private val generateLineNumbers: Boolean,
) : ClassGeneratorExtension {
  private val generators: Set<TMHAssertionGenerator2> by lazy { findGenerators() }

  override fun generateClass(generator: ClassGenerator, declaration: IrClass?): ClassGenerator {
    if (declaration == null || generators.isEmpty()) {
      return generator
    }
    return TmhAssertionsClassGenerator(generator, generators, generateLineNumbers)
  }

  private fun findGenerators(): Set<TMHAssertionGenerator2> {
    val assertionMethods = threadingAssertions.assertionMethods ?: return emptySet()
    return TMHAssertionGenerator2.generators(TMHAssertionGenerator2.OriginKind.KOTLIN)
      .filterTo(HashSet()) { it.hasAssertionMethod(assertionMethods) }
  }
}
