/**
 * Shows the value generated by `enum.auto()` as an inlay hint next to the member declaration.
 *
 * The value is computed statically following the semantics of `Enum._generate_next_value_`:
 * - for a plain `Enum`/`IntEnum`: the previous integer value plus one (starting from `1`);
 * - for a `Flag`/`IntFlag`: the next power of two;
 * - for a `StrEnum`: the lower-cased member name.
 *
 * No hint is shown when the value cannot be determined statically (a custom `_generate_next_value_`,
 * a preceding member whose value is not a literal, etc.).
 *
 * For example:
 * ```
 * class E(Enum):
 *     A = auto()  # = 1
 *     B = auto()  # = 2
 *     C = auto()  # = 3
 * ```
 */
class PyEnumAutoValueInlayHintsProvider : InlayHintsProvider {
  override fun createCollector(file: PsiFile, editor: Editor): InlayHintsCollector = Collector()

  private class Collector : SharedBypassCollector {
    /** Per-file cache: auto member -> rendered hint text, computed lazily for the whole enum class at once. */
    private val cache = HashMap<PyClass, Map<PyTargetExpression, String>>()

    override fun collectFromElement(element: PsiElement, sink: InlayTreeSink) {
      if (element !is PyTargetExpression) return
      // Cheap pre-filter: only members assigned an `auto()` call are interesting.
      val assignedValue = element.findAssignedValue() as? PyCallExpression ?: return
      val enumClass = ScopeUtil.getScopeOwner(element) as? PyClass ?: return

      val hint = cache.getOrPut(enumClass) { computeAutoValues(enumClass) }[element] ?: return

      sink.addPresentation(
        position = InlineInlayPosition(assignedValue.endOffset, true),
        hintFormat = HintFormat.default,
        tooltip = PyPsiBundle.message("INLAY.enum.auto.value.tooltip"),
      ) {
        text(hint)
      }
    }

    private fun computeAutoValues(enumClass: PyClass): Map<PyTargetExpression, String> {
      val context = TypeEvalContext.codeAnalysis(enumClass.project, enumClass.containingFile)
      if (!PyStdlibTypeProvider.isCustomEnum(enumClass, context)) return emptyMap()
      val kind = autoValueKind(enumClass, context) ?: return emptyMap()

      val result = HashMap<PyTargetExpression, String>()
      val lastValues = ArrayList<MemberValue>()

      for (attribute in enumClass.classAttributes) {
        val info = PyStdlibTypeProvider.getEnumAttributeInfo(enumClass, attribute, context)
        if (info == null || info.attributeKind == EnumAttributeKind.NONMEMBER) continue

        val name = attribute.name
        val value = attribute.findAssignedValue()

        if (name != null && isEnumAutoCall(value, context)) {
          when (kind) {
            AutoKind.STR -> {
              result[attribute] = " = '${name.lowercase()}'"
              lastValues.add(MemberValue.NonInt)
            }
            AutoKind.INT -> {
              val next = nextIntValue(lastValues)
              if (next != null) {
                result[attribute] = " = $next"
                lastValues.add(MemberValue.Int(next))
              }
              else {
                lastValues.add(MemberValue.Unknown)
              }
            }
            AutoKind.FLAG -> {
              val next = nextFlagValue(lastValues)
              if (next != null) {
                result[attribute] = " = $next"
                lastValues.add(MemberValue.Int(next))
              }
              else {
                lastValues.add(MemberValue.Unknown)
              }
            }
          }
        }
        else {
          lastValues.add(evaluate(value))
        }
      }
      return result
    }

    private fun autoValueKind(enumClass: PyClass, context: TypeEvalContext): AutoKind? {
      // `Flag`/`IntFlag` generate powers of two; they don't override `_generate_next_value_` in typeshed.
      if (enumClass.isSubclass(PyNames.TYPE_ENUM_FLAG, context)) return AutoKind.FLAG

      val generateNextValue = enumClass.findMethodByName(GENERATE_NEXT_VALUE, true, context) ?: return null
      return when (generateNextValue.containingClass?.qualifiedName) {
        PyNames.TYPE_ENUM -> AutoKind.INT
        STR_ENUM -> AutoKind.STR
        else -> null // a custom `_generate_next_value_`: cannot compute statically
      }
    }

    private fun isEnumAutoCall(value: PyExpression?, context: TypeEvalContext): Boolean {
      val call = value as? PyCallExpression ?: return false
      val callee = call.callee as? PyReferenceExpression ?: return false
      val resolveContext = PyResolveContext.defaultContext(context)
      return callee.getReference(resolveContext).multiResolve(false).any {
        val resolved = it.element
        resolved is PyClass && PyNames.TYPE_ENUM_AUTO == resolved.qualifiedName
      }
    }

    /** Mirrors the default `Enum._generate_next_value_`: most recent integer value plus one, or `1` to start. */
    private fun nextIntValue(lastValues: List<MemberValue>): Long? {
      for (value in lastValues.asReversed()) {
        when (value) {
          is MemberValue.Int -> return value.value + 1
          MemberValue.NonInt -> continue // non-integer values raise `TypeError` at runtime and are skipped
          MemberValue.Unknown -> return null // an unevaluable value: bail to avoid showing a wrong hint
        }
      }
      return 1
    }

    /** Mirrors `Flag._generate_next_value_`: the next power of two above the highest value seen so far. */
    private fun nextFlagValue(lastValues: List<MemberValue>): Long? {
      if (lastValues.isEmpty()) return 1
      var max = -1L
      for (value in lastValues) {
        if (value !is MemberValue.Int) return null
        if (value.value > max) max = value.value
      }
      if (max < 0) return null
      val bitLength = java.lang.Long.SIZE - java.lang.Long.numberOfLeadingZeros(max)
      if (bitLength >= java.lang.Long.SIZE - 1) return null // guard against overflow for unrealistically large flags
      return 1L shl bitLength
    }

    private fun evaluate(value: PyExpression?): MemberValue {
      return when (val expression = PyPsiUtils.flattenParens(value)) {
        is PyNumericLiteralExpression ->
          if (expression.isIntegerLiteral) expression.longValue?.let { MemberValue.Int(it) } ?: MemberValue.Unknown
          else MemberValue.NonInt
        is PyPrefixExpression -> {
          if (expression.operator == PyTokenTypes.MINUS) {
            val operand = PyPsiUtils.flattenParens(expression.operand)
            if (operand is PyNumericLiteralExpression && operand.isIntegerLiteral) {
              operand.longValue?.let { MemberValue.Int(-it) } ?: MemberValue.Unknown
            }
            else MemberValue.Unknown
          }
          else MemberValue.Unknown
        }
        is PyStringLiteralExpression, is PyTupleExpression -> MemberValue.NonInt
        else -> MemberValue.Unknown
      }
    }
  }

  private enum class AutoKind { INT, FLAG, STR }

  private sealed interface MemberValue {
    /** A statically known integer value. */
    data class Int(val value: Long) : MemberValue

    /** A statically known non-integer value (string, tuple, ...). */
    object NonInt : MemberValue

    /** A value that could not be evaluated statically. */
    object Unknown : MemberValue
  }

  private companion object {
    private const val GENERATE_NEXT_VALUE = "_generate_next_value_"
    private const val STR_ENUM = "enum.StrEnum"
  }
}
