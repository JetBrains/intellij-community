private const val OUTPUT_FILE_PATH =
    "platform/jewel/ui/generated/theme/org/jetbrains/jewel/ui/theme/DefaultColorPalette.kt"

// Run it like: bazel run //platform/jewel/build-scripts/bazel:generateDefaultColorPalette
fun main(args: Array<String>) {
    DefaultColorPaletteGeneratorCommand().main(args)
}

internal class DefaultColorPaletteGeneratorCommand : CliktCommand(name = "generate-default-color-palette") {
    override fun help(context: Context): String =
        "Generates DefaultColorPalette.kt for the :ui module from the registered theme JSON sources."

    override fun run() {
        val communityRoot = getBuildWorkspaceDirectory()
        val ijpMajor = readIjpMajor(communityRoot)

        val sources =
            paletteSourceConfigs.map { config ->
                PaletteSource(File(communityRoot, config.themeFilePath), config.propertyName, config.islands)
            }

        val file = readPaletteFrom(sources, ijpMajor)

        val outputFile = File(communityRoot, OUTPUT_FILE_PATH)
        outputFile.parentFile.mkdirs()
        outputFile.writeText(formatKotlinSource(file.toString()))

        println("Generated ${outputFile.relativeTo(communityRoot)}")
    }
}

internal data class PaletteSource(val themeFile: File, val propertyName: String, val islands: Boolean)

@Serializable internal data class IntelliJColors(val colors: Map<String, String> = emptyMap())

private val json = Json { ignoreUnknownKeys = true }
private val colorClassName = ClassName("androidx.compose.ui.graphics", "Color")
private val colorPaletteClassName = ClassName.bestGuess("org.jetbrains.jewel.foundation.theme.ThemeColorPalette")
private val defaultColorPaletteClassName = ClassName("org.jetbrains.jewel.ui.theme", "DefaultColorPalette")
private val internalJewelApiClassName = ClassName.bestGuess("org.jetbrains.jewel.foundation.InternalJewelApi")
private val apiStatusInternalClassName = ClassName("org.jetbrains.annotations", "ApiStatus", "Internal")
private val colorGroups = setOf("Gray", "Blue", "Green", "Red", "Yellow", "Orange", "Purple", "Teal")

internal fun readPaletteFrom(sources: List<PaletteSource>, ijpMajor: String): FileSpec =
    FileSpec.builder(defaultColorPaletteClassName)
        .apply {
            addFileComment("Generated by the Jewel Int UI Color Palette Generator for IJP $ijpMajor\n")
            addFileComment("*** DO NOT EDIT MANUALLY!***\n")
            addFileComment(
                "Run the generateDefaultColorPalette target in platform/jewel/build-scripts/bazel/BUILD.bazel to update."
            )

            addImport(colorClassName.packageName, colorClassName.simpleName)

            addType(
                TypeSpec.objectBuilder(defaultColorPaletteClassName)
                    .addAnnotation(AnnotationSpec.builder(Suppress::class).addMember("%S", "LargeClass").build())
                    .addAnnotation(apiStatusInternalClassName)
                    .addAnnotation(internalJewelApiClassName)
                    .apply { sources.forEach { source -> addPaletteProperty(source) } }
                    .build()
            )
        }
        .build()

@OptIn(ExperimentalSerializationApi::class)
internal fun TypeSpec.Builder.addPaletteProperty(source: PaletteSource) {
    val colors = source.themeFile.inputStream().use { json.decodeFromStream<IntelliJColors>(it) }.colors

    addProperty(
        PropertySpec.builder(source.propertyName, colorPaletteClassName)
            .initializer(
                "ThemeColorPalette(%L,\n%L,\nisIslands = %L\n)",
                buildColorGroupBlocks(colors).joinToCode(","),
                buildRawMapBlock(colors),
                source.islands,
            )
            .build()
    )
}

/** Groups colors by family (e.g. "Gray1"/"gray-160" both group under "Gray"), sorted ascending by index. */
internal fun buildColorGroupBlocks(colors: Map<String, String>): List<CodeBlock> =
    colors.entries
        .groupBy { it.key.replace("""-?\d+$""".toRegex(), "").replaceFirstChar { c -> c.uppercase() } }
        .filterKeys { colorGroups.contains(it) }
        .mapValues { (_, entries) -> entries.sortedBy { it.key.takeLastWhile(Char::isDigit).toInt() } }
        .map { (groupName, entries) ->
            entries
                .map { (_, value) -> CodeBlock.of("Color(%L)", resolveHex(value, colors).replace("#", "0xFF")) }
                .joinToCode(prefix = "\n${groupName.lowercase()} = listOf(\n", separator = ",\n", suffix = "\n)")
        }

internal fun buildRawMapBlock(colors: Map<String, String>): CodeBlock =
    colors.entries
        .map { (key, value) -> CodeBlock.of("%S to Color(%L)", key, resolveHex(value, colors).replace("#", "0xFF")) }
        .joinToCode(prefix = "\nrawMap = mapOf(\n", separator = ",\n", suffix = "\n)")

/**
 * Some theme JSONs (notably the Islands ones) define colors as aliases pointing at another key instead of a literal hex
 * value (e.g. "toggle-off-bg": "gray-160"), sometimes several levels deep. Follows the chain down to an actual hex
 * value.
 */
internal fun resolveHex(value: String, colors: Map<String, String>, depth: Int = 0): String {
    if (value.startsWith("#")) return value
    check(depth < 10) { "Color alias chain too deep (possible cycle) resolving '$value'" }

    val aliased = colors[value] ?: error("Unresolved color alias '$value'")
    return resolveHex(aliased, colors, depth + 1)
}
