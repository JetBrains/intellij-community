// Hardcoded from the intelliJThemeGenerator registrations in
// platform/jewel/int-ui/int-ui-standalone/build.gradle.kts, the only caller site.
private data class ThemeConfig(val themeClassName: String, val themeFilePath: String)

private val themeConfigs =
    listOf(
        ThemeConfig(
            themeClassName = "org.jetbrains.jewel.intui.core.theme.IntUiLightTheme",
            themeFilePath = "platform/platform-resources/src/themes/expUI/expUI_light.theme.json",
        ),
        ThemeConfig(
            themeClassName = "org.jetbrains.jewel.intui.core.theme.IntUiDarkTheme",
            themeFilePath = "platform/platform-resources/src/themes/expUI/expUI_dark.theme.json",
        ),
    )

private const val TARGET_DIR = "platform/jewel/int-ui/int-ui-standalone/generated/theme"

// Run it like: bazel run //platform/jewel/build-scripts/bazel:generateIntelliJTheme
fun main(args: Array<String>) {
    IntelliJThemeGeneratorCommand().main(args)
}

internal class IntelliJThemeGeneratorCommand : CliktCommand(name = "generate-intellij-theme") {
    override fun help(context: Context): String =
        "Generates IntUiLightTheme.kt/IntUiDarkTheme.kt for the :int-ui-standalone module from the registered " +
            "theme JSON sources."

    @OptIn(ExperimentalSerializationApi::class)
    override fun run() {
        val communityRoot = getBuildWorkspaceDirectory()
        val ijpMajor = readIjpMajor(communityRoot)
        val json = Json { ignoreUnknownKeys = true }

        themeConfigs.forEach { config ->
            val className = ClassName.bestGuess(config.themeClassName)
            val themeFile = File(communityRoot, config.themeFilePath)

            println("Fetching theme descriptor from ${themeFile.name}...")
            val themeDescriptor = themeFile.inputStream().use { json.decodeFromStream<IntellijThemeDescriptor>(it) }

            val file = readThemeFrom(themeDescriptor, className, config.themeFilePath, ijpMajor)

            val outputPath = className.packageName.replace(".", "/") + "/${className.simpleName}.kt"
            val outputFile = File(communityRoot, "$TARGET_DIR/$outputPath")
            outputFile.parentFile.mkdirs()
            outputFile.writeText(formatKotlinSource(file.toString()))

            println(
                "Theme descriptor for ${themeDescriptor.name} parsed and code generated into " +
                    "${outputFile.relativeTo(communityRoot)}"
            )
        }
    }
}

@Serializable
internal data class IntellijThemeDescriptor(
    val name: String,
    val author: String = "",
    val dark: Boolean = false,
    val editorScheme: String,
    val colors: Map<String, String> = emptyMap(),
    val ui: Map<String, JsonElement> = emptyMap(),
    val icons: Map<String, JsonElement> = emptyMap(),
    val iconColorsOnSelection: Map<String, Int> = emptyMap(),
)

private val defaultColorPaletteClassName = ClassName("org.jetbrains.jewel.ui.theme", "DefaultColorPalette")
private val colorPaletteClassName = ClassName.bestGuess("org.jetbrains.jewel.foundation.theme.ThemeColorPalette")
private val iconDataClassName = ClassName.bestGuess("org.jetbrains.jewel.foundation.theme.ThemeIconData")
private val internalJewelApiClassName = ClassName.bestGuess("org.jetbrains.jewel.foundation.InternalJewelApi")
private val themeDescriptorClassName = ClassName.bestGuess("org.jetbrains.jewel.foundation.theme.ThemeDescriptor")

internal fun readThemeFrom(
    themeDescriptor: IntellijThemeDescriptor,
    className: ClassName,
    sourcePath: String,
    ijpMajor: String,
): FileSpec =
    FileSpec.builder(className)
        .apply {
            indent("    ")
            addFileComment("Generated by the Jewel Int UI Palette Generator for IJP $ijpMajor\n")
            addFileComment("*** DO NOT EDIT MANUALLY! ***\n")
            addFileComment(
                "Run the generateIntelliJTheme target in platform/jewel/build-scripts/bazel/BUILD.bazel to update.\n"
            )
            addFileComment("Source: $sourcePath")

            addType(
                TypeSpec.objectBuilder(className)
                    .apply {
                        addSuperinterface(themeDescriptorClassName)

                        addProperty(
                            PropertySpec.builder("isDark", Boolean::class, KModifier.OVERRIDE)
                                .initializer("%L", themeDescriptor.dark)
                                .build()
                        )

                        addProperty(
                            PropertySpec.builder("name", String::class, KModifier.OVERRIDE)
                                .initializer("\"%L (Int UI)\"", themeDescriptor.name)
                                .build()
                        )

                        addColorsProperty(themeDescriptor.dark)
                        addIconDataProperty(themeDescriptor)
                    }
                    .build()
            )
        }
        .build()

internal fun TypeSpec.Builder.addColorsProperty(isDark: Boolean) {
    addProperty(
        PropertySpec.builder("colors", colorPaletteClassName, KModifier.OVERRIDE)
            .addAnnotation(
                AnnotationSpec.builder(ClassName("kotlin", "OptIn"))
                    .addMember("%T::class", internalJewelApiClassName)
                    .build()
            )
            .initializer("%T.%L", defaultColorPaletteClassName, if (isDark) "Dark" else "Light")
            .build()
    )
}

internal fun TypeSpec.Builder.addIconDataProperty(theme: IntellijThemeDescriptor) {
    val iconOverrides = mutableMapOf<String, String>()
    val colorPalette = mutableMapOf<String, String>()

    for ((key, value) in theme.icons) {
        if (value is JsonPrimitive && value.isString) {
            iconOverrides += key to value.content
        } else if (value is JsonObject && key == "ColorPalette") {
            value.entries
                .mapNotNull {
                    val pairValue = it.value
                    if (pairValue is JsonPrimitive && pairValue.isString) {
                        it.key to pairValue.content
                    } else {
                        null
                    }
                }
                .forEach { colorPalette[it.first] = it.second }
        }
    }

    val iconOverridesBlock = iconOverrides.toMapCodeBlock()
    val selectionColorPaletteBlock = theme.iconColorsOnSelection.toMapCodeBlock()

    addProperty(
        PropertySpec.builder("iconData", iconDataClassName, KModifier.OVERRIDE)
            .initializer(
                CodeBlock.of(
                    "ThemeIconData(\niconOverrides = \n%L,\ncolorPalette = \n%L,\nselectionColorPalette = %L\n)",
                    iconOverridesBlock,
                    colorPalette.toMapCodeBlock(),
                    selectionColorPaletteBlock,
                )
            )
            .build()
    )
}

internal fun <K, V> Map<K, V>.toMapCodeBlock(): CodeBlock {
    if (entries.isEmpty()) return CodeBlock.of("emptyMap()")

    return entries
        .map { (key, value) -> CodeBlock.of("\"%L\" to \"%L\"", key, value) }
        .joinToCode(prefix = "mapOf(", separator = ",\n", suffix = ")")
}
