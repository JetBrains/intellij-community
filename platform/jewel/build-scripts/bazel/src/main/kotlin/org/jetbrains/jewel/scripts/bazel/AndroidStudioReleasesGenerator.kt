private const val DATA_URL = "https://jb.gg/android-studio-releases-list.json"
private const val OUTPUT_CLASS_NAME = "com.intellij.devkit.compose.demo.releasessample.AndroidStudioReleases"
private const val MODEL_PACKAGE = "com.intellij.devkit.compose.demo.releasessample"
private const val INDENT = "  "
private const val OUTPUT_FILE_PATH =
    "plugins/devkit/intellij.devkit.compose/src/demo/releasessample/AndroidStudioReleases.kt"
private const val RESOURCES_DIR_PATH = "plugins/devkit/intellij.devkit.compose/resources"

// Run it like: bazel run //platform/jewel/build-scripts/bazel:generateAndroidStudioReleasesList
fun main(args: Array<String>) {
    AndroidStudioReleasesGeneratorCommand().main(args)
}

internal class AndroidStudioReleasesGeneratorCommand : CliktCommand(name = "generate-android-studio-releases") {
    override fun help(context: Context): String =
        "Generates AndroidStudioReleases.kt for the DevKit Compose demo from the latest Android Studio releases list."

    @OptIn(ExperimentalSerializationApi::class)
    override fun run() {
        val communityRoot = getBuildWorkspaceDirectory()
        val json = Json {
            ignoreUnknownKeys = true
            isLenient = true
        }

        println("Fetching Android Studio releases list from $DATA_URL...")
        val releases =
            URI.create(DATA_URL).toURL().openStream().use { json.decodeFromStream<ApiAndroidStudioReleases>(it) }

        val className = ClassName.bestGuess(OUTPUT_CLASS_NAME)
        val resourceDirs = setOf(File(communityRoot, RESOURCES_DIR_PATH))

        val file = readFrom(releases, className, DATA_URL, resourceDirs, MODEL_PACKAGE, INDENT)

        val outputFile = File(communityRoot, OUTPUT_FILE_PATH)
        outputFile.parentFile.mkdirs()
        outputFile.writeText(formatKotlinSource(file.toString()))

        println(
            "Android Studio releases from $DATA_URL parsed and code generated into " +
                "${outputFile.relativeTo(communityRoot)}"
        )
    }
}

@Serializable
internal data class ApiAndroidStudioReleases(@SerialName("content") val content: Content = Content()) {
    @Serializable
    internal data class Content(
        @SerialName("item") val item: List<Item> = listOf(),
        @SerialName("version") val version: Int = 0,
    ) {
        @Serializable
        internal data class Item(
            @SerialName("build") val build: String,
            @SerialName("channel") val channel: String,
            @SerialName("date") val date: String,
            @SerialName("download") val download: List<Download> = listOf(),
            @SerialName("name") val name: String,
            @SerialName("platformBuild") val platformBuild: String,
            @SerialName("platformVersion") val platformVersion: String?,
            @SerialName("version") val version: String,
        ) {
            @Serializable
            internal data class Download(
                @SerialName("checksum") val checksum: String,
                @SerialName("link") val link: String,
                @SerialName("size") val size: String,
            )
        }
    }
}

internal fun readFrom(
    releases: ApiAndroidStudioReleases,
    className: ClassName,
    url: String,
    resourceDirs: Set<File>,
    modelPackage: String = MODEL_PACKAGE,
    indentString: String = "    ",
): FileSpec =
    FileSpec.builder(className)
        .apply {
            indent(indentString)
            addFileComment("Generated by the Jewel Android Studio Releases Generator\n")
            addFileComment("Generated from $url on ${ZonedDateTime.now()}")

            addImport(modelPackage, "ContentItem.AndroidStudio")
            addImport("kotlinx.datetime", "LocalDate")

            addType(createBaseTypeSpec(className, releases, resourceDirs, modelPackage))
        }
        .build()

private fun createBaseTypeSpec(
    className: ClassName,
    releases: ApiAndroidStudioReleases,
    resourceDirs: Set<File>,
    modelPackage: String,
): TypeSpec {
    val contentItemClassName = ClassName.bestGuess("$modelPackage.ContentItem.AndroidStudio")
    return TypeSpec.objectBuilder(className)
        .addModifiers(KModifier.INTERNAL)
        .superclass(ClassName.bestGuess("$modelPackage.ContentSource").parameterizedBy(contentItemClassName))
        .apply {
            addProperty(
                PropertySpec.builder(
                        name = "items",
                        type = List::class.asClassName().parameterizedBy(contentItemClassName),
                        KModifier.OVERRIDE,
                    )
                    .initializer(readReleases(releases, resourceDirs))
                    .build()
            )

            addProperty(
                PropertySpec.builder("displayName", type = String::class.asClassName(), KModifier.OVERRIDE)
                    .initializer("\"%L\"", "Android Studio releases")
                    .build()
            )
        }
        .build()
}

internal fun readReleases(releases: ApiAndroidStudioReleases, resourceDirs: Set<File>): CodeBlock =
    releases.content.item
        .map { readRelease(it, resourceDirs) }
        .joinToCode(prefix = "listOf(\n", separator = ",\n", suffix = ")")

internal fun readRelease(release: ApiAndroidStudioReleases.Content.Item, resourceDirs: Set<File>): CodeBlock =
    CodeBlock.builder()
        .apply {
            add("AndroidStudio(\n")
            add("    displayText = \"%L\",\n", displayTextFor(release.name))
            add("    imagePath = %L,\n", imagePathForOrNull(release, resourceDirs))
            add("    versionName = \"%L\",\n", release.version)
            add("    build = \"%L\",\n", release.build)
            add("    platformBuild = \"%L\",\n", release.platformBuild)
            add("    platformVersion = \"%L\",\n", release.platformVersion ?: "N/A")
            add("    channel = %L,\n", readChannel(release.channel))
            add("    releaseDate = LocalDate(%L),\n", translateDate(release.date))
            add("    key = \"%L\",\n", release.build)
            add(")")
        }
        .build()

internal fun imagePathForOrNull(release: ApiAndroidStudioReleases.Content.Item, resourceDirs: Set<File>): String? {
    // Take the release animal from the name, remove spaces and voila'
    val releaseAnimal =
        release.name
            .substringBefore(" | ")
            .substringAfter("Android Studio")
            .trim()
            .withoutDropCounter()
            .replace(" ", "")

    if (releaseAnimal.isEmpty() || releaseAnimal.any { it.isDigit() }) return null

    // We only have stable and canary splash screens. Betas use the stable ones.
    val channel =
        release.channel.lowercase().let {
            when (it) {
                "release",
                "rc",
                "stable",
                "beta",
                "patch" -> "stable"
                "canary",
                "preview",
                "alpha" -> "canary"
                else -> {
                    println("  Note: channel '${it}' isn't supported for splash screens")
                    null
                }
            }
        } ?: return null

    val splashPath = "/studio-splash-screens/$releaseAnimal-$channel.png"
    val splashFiles = resourceDirs.map { dir -> File(dir, splashPath) }
    if (splashFiles.none { it.isFile }) {
        println("  Note: expected splash screen file doesn't exist: '${splashPath}'")
        return null
    }

    return "\"$splashPath\""
}

// Releases starting from Panda carry a digit along their name (e.g., "Quail 3"), so we remove those
internal fun String.withoutDropCounter(): String =
    split(' ').filterNot { it.isEmpty() || it.all(Char::isDigit) }.joinToString(separator = " ")

// Only names with a version part (e.g., "Android Studio Quail 3 | 2026.1.3") carry a drop counter;
// older ones are version-only ("Android Studio 2.4 Preview 4") and must be left alone
internal fun displayTextFor(name: String): String {
    val releaseName = name.substringBefore(" | ")
    if (releaseName == name) return name
    return "${releaseName.withoutDropCounter()} | ${name.substringAfter(" | ")}"
}

internal fun translateDate(rawDate: String): String {
    val formatter = DateTimeFormatter.ofPattern("MMMM d, uuuu")
    val parsedDate = LocalDate.parse(rawDate, formatter)

    return "${parsedDate.year}, ${parsedDate.monthValue}, ${parsedDate.dayOfMonth}"
}

internal fun readChannel(rawChannel: String): String =
    when (rawChannel.lowercase().trim()) {
        "stable",
        "patch",
        "release" -> "ReleaseChannel.Stable"
        "beta" -> "ReleaseChannel.Beta"
        "canary" -> "ReleaseChannel.Canary"
        else -> "ReleaseChannel.Other"
    }
