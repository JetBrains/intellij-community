abstract class PaletteSource {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val themeFile: RegularFileProperty

    @get:Input
    abstract val propertyName: Property<String>

    @get:Input
    abstract val islands: Property<Boolean>
}

abstract class DefaultColorPaletteGeneratorTask : DefaultTask() {
    @get:Nested
    abstract val sources: ListProperty<PaletteSource>

    @get:OutputFile
    abstract val outputFile: RegularFileProperty

    @TaskAction
    fun generate() {
        val file = DefaultColorPaletteReader.readPaletteFrom(sources.get(), readIjpMajor())
        outputFile.get().asFile.bufferedWriter().use { file.writeTo(it) }
    }

    private fun readIjpMajor(): String {
        val buildNumberFile = project.rootDir.resolve("../../build.txt")
        check(buildNumberFile.isFile) { "The build.txt file must exist in the community root" }

        val buildNumber = buildNumberFile.readText().trim()
        check(validateBuildNumber(buildNumber)) { "The build number in build.txt does not seem valid: '$buildNumber'" }

        return buildNumber.substringBefore('.')
    }

    private fun validateBuildNumber(buildNumber: String): Boolean {
        // Examples:
        //  * 253.1234.567
        //  * 241.SNAPSHOT
        //  * 253.28294.SNAPSHOT
        if (buildNumber.isBlank()) return false
        if (buildNumber.length < 5) return false
        if (buildNumber.take(3).toIntOrNull()?.takeIf { it > 240 } == null) return false
        if (buildNumber[3] != '.') return false

        val afterDot = buildNumber.drop(4)
        return afterDot == "SNAPSHOT" ||
            afterDot.all { it.isDigit() || it == '.' } ||
            (afterDot.endsWith(".SNAPSHOT") && afterDot.removeSuffix(".SNAPSHOT").all { it.isDigit() || it == '.' })
    }
}

internal object DefaultColorPaletteReader {
    private val json = Json { ignoreUnknownKeys = true }
    private val colorClassName = ClassName("androidx.compose.ui.graphics", "Color")
    private val colorPaletteClassName = ClassName.bestGuess("org.jetbrains.jewel.foundation.theme.ThemeColorPalette")
    private val defaultColorPaletteClassName = ClassName("org.jetbrains.jewel.ui.theme", "DefaultColorPalette")
    private val internalJewelApiClassName = ClassName.bestGuess("org.jetbrains.jewel.foundation.InternalJewelApi")
    private val apiStatusInternalClassName = ClassName("org.jetbrains.annotations", "ApiStatus", "Internal")
    private val colorGroups = setOf("Gray", "Blue", "Green", "Red", "Yellow", "Orange", "Purple", "Teal")

    fun readPaletteFrom(sources: List<PaletteSource>, ijpMajor: String): FileSpec =
        FileSpec.builder(defaultColorPaletteClassName)
            .apply {
                addFileComment("Generated by the Jewel Int UI Color Palette Generator for IJP $ijpMajor\n")
                addFileComment("*** DO NOT EDIT MANUALLY! Use intelliJColorPaletteGenerator task to update. ***\n")

                addImport(colorClassName.packageName, colorClassName.simpleName)

                addType(
                    TypeSpec.objectBuilder(defaultColorPaletteClassName)
                        .addAnnotation(
                            AnnotationSpec.builder(Suppress::class).addMember("%S", "LargeClass").build()
                        )
                        .addAnnotation(apiStatusInternalClassName)
                        .addAnnotation(internalJewelApiClassName)
                        .apply { sources.forEach { source -> addPaletteProperty(source) } }
                        .build()
                )
            }
            .build()

    private fun TypeSpec.Builder.addPaletteProperty(source: PaletteSource) {
        val colors =
            source.themeFile.get().asFile.inputStream().use { json.decodeFromStream<IntelliJColors>(it) }.colors

        addProperty(
            PropertySpec.builder(source.propertyName.get(), colorPaletteClassName)
                .initializer(
                    "ThemeColorPalette(%L,\n%L,\nisIslands = %L\n)",
                    buildColorGroupBlocks(colors).joinToCode(","),
                    buildRawMapBlock(colors),
                    source.islands.get(),
                )
                .build()
        )
    }

    /** Groups colors by family (e.g. "Gray1"/"gray-160" both group under "Gray"), sorted ascending by index. */
    private fun buildColorGroupBlocks(colors: Map<String, String>): List<CodeBlock> =
        colors.entries
            .groupBy { it.key.replace("""-?\d+$""".toRegex(), "").replaceFirstChar { c -> c.uppercase() } }
            .filterKeys { colorGroups.contains(it) }
            .mapValues { (_, entries) -> entries.sortedBy { it.key.takeLastWhile(Char::isDigit).toInt() } }
            .map { (groupName, entries) ->
                entries
                    .map { (_, value) -> CodeBlock.of("Color(%L)", resolveHex(value, colors).replace("#", "0xFF")) }
                    .joinToCode(prefix = "\n${groupName.lowercase()} = listOf(\n", separator = ",\n", suffix = "\n)")
            }

    private fun buildRawMapBlock(colors: Map<String, String>): CodeBlock =
        colors.entries
            .map { (key, value) -> CodeBlock.of("%S to Color(%L)", key, resolveHex(value, colors).replace("#", "0xFF")) }
            .joinToCode(prefix = "\nrawMap = mapOf(\n", separator = ",\n", suffix = "\n)")

    /**
     * Some theme JSONs (notably the Islands ones) define colors as aliases pointing at another key instead of a
     * literal hex value (e.g. "toggle-off-bg": "gray-160"), sometimes several levels deep. Follows the chain down to
     * an actual hex value.
     */
    private fun resolveHex(value: String, colors: Map<String, String>, depth: Int = 0): String {
        if (value.startsWith("#")) return value
        check(depth < 10) { "Color alias chain too deep (possible cycle) resolving '$value'" }

        val aliased = colors[value] ?: error("Unresolved color alias '$value'")
        return resolveHex(aliased, colors, depth + 1)
    }
}

@Serializable
data class IntelliJColors(
    val colors: Map<String, String> = emptyMap(),
)
