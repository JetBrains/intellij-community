package org.jetbrains.intellij.build.impl.plugins

import com.charleskorn.kaml.SingleLineStringStyle
import com.charleskorn.kaml.Yaml
import com.charleskorn.kaml.YamlConfiguration
import com.charleskorn.kaml.decodeFromStream
import kotlinx.serialization.Serializable
import org.jetbrains.intellij.build.generateInclusionReasonForContentModule
import org.jetbrains.intellij.build.impl.ModuleItem
import org.jetbrains.intellij.build.impl.projectStructureMapping.DistributionFileEntry
import org.jetbrains.intellij.build.impl.projectStructureMapping.ModuleOutputEntry
import java.nio.file.Path
import kotlin.io.path.inputStream

/**
 * Parses content of `plugin-content.yaml` produced by `ij_plugin` Bazel rule to the form that can be used by the build scripts
 */
internal fun parsePluginContentYaml(pluginContentYamlPath: Path, pluginMainModule: String, pluginDistributionDirectory: Path): List<DistributionFileEntry> {
  val fileEntries = pluginContentYamlPath.inputStream().buffered().use {
    yaml.decodeFromStream<List<PluginContentFileEntry>>(it)
  }
  return fileEntries.asSequence().flatMap { entry ->
    val relativeJarPath = entry.name
    entry.modules.asSequence().map { convertModuleEntry(it, relativeJarPath, pluginMainModule, isContentModule = false, pluginDistributionDirectory) } +
    entry.contentModules.asSequence().map { convertModuleEntry(it, relativeJarPath, pluginMainModule, isContentModule = true, pluginDistributionDirectory) }
  }.toList()
}

private fun convertModuleEntry(
  pluginContentModuleEntry: PluginContentModuleEntry,
  relativeJarPath: String,
  pluginMainModule: String,
  isContentModule: Boolean,
  pluginDistributionDirectory: Path
): ModuleOutputEntry {
  val moduleItem = ModuleItem(
    moduleName = pluginContentModuleEntry.name,
    relativeOutputFile = relativeJarPath.removePrefix("lib/"),
    reason = if (isContentModule) generateInclusionReasonForContentModule(pluginMainModule) else null,
  )
  return ModuleOutputEntry(
    path = pluginDistributionDirectory.resolve(relativeJarPath),
    owner = moduleItem,
    size = 0,
    hash = 0,
    relativeOutputFile = moduleItem.relativeOutputFile,
    reason = moduleItem.reason,
  )
}


private val yaml = Yaml(
  configuration = YamlConfiguration(
    encodeDefaults = false,
    singleLineStringStyle = SingleLineStringStyle.PlainExceptAmbiguous,
  ),
)

/**
 * Represents a subset of [com.intellij.platform.distributionContent.testFramework.FileEntry] that can be used in `plugin-content.yaml` generated by `ij_plugin` rule
 */
@Serializable
private class PluginContentFileEntry(
  @JvmField val name: String,
  @JvmField val modules: List<PluginContentModuleEntry> = emptyList(),
  @JvmField val contentModules: List<PluginContentModuleEntry> = emptyList(),
)

@Serializable
private class PluginContentModuleEntry(
  @JvmField val name: String
)
