package org.jetbrains.intellij.build.bazel

import java.nio.file.Files
import java.nio.file.Path
import java.util.concurrent.ConcurrentHashMap
import kotlin.io.path.createParentDirectories
import kotlin.io.path.writeText

internal class BazelFileUpdater(private val file: Path) {
  private var originalContent: String? = runCatching { Files.readString(file) }.getOrNull()
  private var fileContent: String? = originalContent

  fun removeSections(sectionNamePrefix: String) {
    val fileContent = fileContent ?: return
    // Compiled once per prefix, not once per (prefix, file): a run removes the same handful of prefixes from
    // thousands of BUILD files.
    val pattern = sectionRemovalPatterns.computeIfAbsent(sectionNamePrefix) {
      Regex("### auto-generated section `$it[^`]*` start[\\s\\S]*?### auto-generated section `$it[^`]*` end")
    }
    this.fileContent = fileContent.replace(pattern, "").trim().takeIf { it.isNotBlank() }
    handWrittenExportedFilesCache = null
  }

  // Asked for more than once per module while the content stands still, so the scan result is kept until the next
  // content mutation.
  private var handWrittenExportedFilesCache: Set<String>? = null

  /**
   * The files this BUILD file exports by hand, outside the generated sections.
   *
   * Bazel rejects a file exported twice in one package, so a generator that also wants to export something has to
   * defer to what a human already wrote - including the narrower visibility they chose.
   *
   * Call after [removeSections], which is what leaves only the hand-written content behind.
   * The returned set is the live cache - do not mutate it.
   */
  fun handWrittenExportedFiles(): Set<String> {
    handWrittenExportedFilesCache?.let { return it }
    val fileContent = fileContent ?: return emptySet()
    val result = HashSet<String>()
    for (block in EXPORTS_FILES_PATTERN.findAll(fileContent)) {
      for (entry in QUOTED_PATTERN.findAll(block.groupValues[1])) {
        result.add(entry.groupValues[1])
      }
    }
    handWrittenExportedFilesCache = result
    return result
  }

  fun isSectionSkipped(sectionName: String): Boolean {
    val fileContent = fileContent ?: return false
    return fileContent.contains("### skip generation section `$sectionName`")
  }

  fun insertAutoGeneratedSection(sectionName: String, autoGeneratedContent: String) {
    require(sectionName.isNotEmpty()) {
      "sectionName must not be empty"
    }
    if (autoGeneratedContent.isEmpty()) {
      return
    }
    handWrittenExportedFilesCache = null

    val startToken = "### auto-generated section `$sectionName` start"
    val endToken = "### auto-generated section `$sectionName` end"

    val newSection = "\n$autoGeneratedContent"
    val fileContent = fileContent
    if (fileContent == null) {
      resetFileContent(startToken = startToken, newSection = newSection, endToken = endToken)
      return
    }

    val startIndex = fileContent.indexOf(startToken)
    val endIndex = fileContent.indexOf(endToken)
    if (startIndex == -1 || endIndex == -1) {
      if (!fileContent.contains("### skip generation section `$sectionName`")) {
        appendFileContent(startToken, newSection, endToken)
      }
    }
    else {
      this.fileContent = fileContent.substring(0, startIndex + startToken.length) + "\n" + newSection.trim() + "\n\n" + fileContent.substring(endIndex)
    }
  }

  private fun resetFileContent(startToken: String, newSection: String, endToken: String) {
    this.fileContent = startToken + "\n" + newSection.trim() + "\n" + endToken
  }

  private fun appendFileContent(startToken: String, newSection: String, endToken: String) {
    if (fileContent?.lastOrNull() != '\n') {
      fileContent = fileContent + "\n"
    }
    fileContent = fileContent + "\n" + startToken + "\n" + newSection.trim() + "\n" + endToken
  }

  fun save() {
    val newContent = fileContent?.trim()?.let { it + "\n" } ?: error("fileContent is not set for $file")
    if (originalContent != newContent) {
      file.createParentDirectories().writeText(newContent)
    }
  }

  fun appendLoadSymbols(existingLoadSymbols: Map<String, Set<String>>) {
    handWrittenExportedFilesCache = null
    val manager = BazelLoadStatementManager()

    manager.insert(existingLoadSymbols)

    originalContent?.lines().orEmpty()
      .filter { isLoadStatementToMove(it) }
      .forEach { manager.insert(it) }

    val stripedContent = fileContent?.lines().orEmpty()
      .filterNot { isLoadStatementToMove(it) }
      .joinToString(separator = "\n")
      .trim()

    val result = manager.getResult()

    fileContent = if (result.isEmpty()) {
      stripedContent
    } else {
      result + "\n\n" + stripedContent
    }
  }

  private fun isLoadStatementToMove(line: String): Boolean {
    return line.startsWith("load(") && !thoseLoadStatementsShouldBeNotMoved.contains(line)
  }

  private val thoseLoadStatementsShouldBeNotMoved = listOf(
    // Referenced in build/BUILD.bazel
    "load(\"//build:dev_server_run_configurations.bzl\", \"dev_server_run_configurations\")"
  )
}

private val EXPORTS_FILES_PATTERN = Regex("""exports_files\(\s*\[([^]]*)]""")
private val QUOTED_PATTERN = Regex("\"([^\"]+)\"")
// Shared across every updater in the JVM; concurrent so a future parallelization of generation cannot corrupt it.
private val sectionRemovalPatterns = ConcurrentHashMap<String, Regex>()
