package org.jetbrains.intellij.build.bazel

import org.junit.Assert.assertEquals
import org.junit.Rule
import org.junit.Test
import org.junit.rules.TemporaryFolder
import java.nio.file.Path
import kotlin.io.path.readText
import kotlin.io.path.writeText

/**
 * A regeneration must drop a load symbol that no rule call in the BUILD file names.
 *
 * A load line can also serve a hand-written rule call, so the test covers both kinds of call.
 */
internal class BazelFileUpdaterLoadSymbolsTest {

  @JvmField
  @Rule
  val tempFolder = TemporaryFolder()

  @Test
  fun `keeps the symbol a hand-written call needs and drops the rest of the line`() {
    val file = buildFile("""
      load("@rules_jvm//:jvm.bzl", "jvm_library", "jvm_provided_library")
      load("@community//platform/build-scripts/bazel-rules:dev_dist_content.bzl", "dev_dist_plugin_content")
      load("//build:hand_written.bzl", "hand_written_rule", my_alias = "aliased_rule")

      hand_written_rule(name = "kept")

      my_alias(name = "also_kept")

      ### auto-generated section `build sample` start
      jvm_provided_library(name = "sample_provided")
      ### auto-generated section `build sample` end
    """.trimIndent())

    val updater = BazelFileUpdater(file)
    updater.insertAutoGeneratedSection(sectionName = "build sample", autoGeneratedContent = """jvm_library(name = "sample")""")
    updater.appendLoadSymbols(mapOf("@rules_jvm//:jvm.bzl" to setOf("jvm_library")))
    updater.save()

    assertEquals("""
      load("@rules_jvm//:jvm.bzl", "jvm_library")
      load("//build:hand_written.bzl", "hand_written_rule", my_alias = "aliased_rule")

      hand_written_rule(name = "kept")

      my_alias(name = "also_kept")

      ### auto-generated section `build sample` start
      jvm_library(name = "sample")

      ### auto-generated section `build sample` end
    """.trimIndent() + "\n", file.readText())
  }

  @Test
  fun `drops the whole line when no symbol on it survives`() {
    val file = buildFile("""
      load("@community//platform/build-scripts/bazel-rules:dev_dist_content.bzl", "dev_dist_plugin_content")
      load("@community//platform/build-scripts/bazel-rules:dev_dist_plugin_descriptor.bzl", "dev_dist_plugin_descriptor")
      load("@community//platform/build-scripts/bazel-rules:dev_dist_plugin.bzl", "dev_dist_plugin")

      dev_dist_plugin(name = "sample_dev_dist")
    """.trimIndent())

    val updater = BazelFileUpdater(file)
    updater.appendLoadSymbols(emptyMap())
    updater.save()

    assertEquals("""
      load("@community//platform/build-scripts/bazel-rules:dev_dist_plugin.bzl", "dev_dist_plugin")

      dev_dist_plugin(name = "sample_dev_dist")
    """.trimIndent() + "\n", file.readText())
  }

  @Test
  fun `drops a symbol the generator asked for but no section calls`() {
    val file = buildFile("""
      jps_test(name = "unrelated_hand_written")
    """.trimIndent())

    val updater = BazelFileUpdater(file)
    updater.appendLoadSymbols(mapOf("@community//build:tests-options.bzl" to setOf("jps_test", "resourcegroup")))
    updater.save()

    assertEquals("""
      load("@community//build:tests-options.bzl", "jps_test")

      jps_test(name = "unrelated_hand_written")
    """.trimIndent() + "\n", file.readText())
  }

  @Test
  fun `keeps every load when the file has no dead symbol`() {
    val content = """
      load("@rules_jvm//:jvm.bzl", "jvm_library")

      jvm_library(name = "sample")
    """.trimIndent()
    val file = buildFile(content)

    val updater = BazelFileUpdater(file)
    updater.appendLoadSymbols(mapOf("@rules_jvm//:jvm.bzl" to setOf("jvm_library")))
    updater.save()

    assertEquals(content + "\n", file.readText())
  }

  private fun buildFile(content: String): Path {
    val file = tempFolder.newFolder().toPath().resolve("BUILD.bazel")
    file.writeText(content + "\n")
    return file
  }
}
